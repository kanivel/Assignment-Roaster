import { HStack, SimpleGrid, Text, VStack } from '@chakra-ui/react'

import type { AdminStats } from '../../types/admin'
import { SUBMISSION_STATUSES } from '../../types/submission'
import { StatCard } from '../dashboard/StatCard'
import { GlassCard } from '../ui/GlassCard'
import { StatusBadge } from '../ui/StatusBadge'

export interface AdminStatCardsProps {
  stats: AdminStats
}

const formatNumber = (value: number): string => value.toLocaleString()

export const AdminStatCards = ({ stats }: AdminStatCardsProps) => {
  const totalSubmissions = Object.values(stats.submissions_by_status).reduce(
    (sum, count) => sum + count,
    0,
  )

  return (
    <VStack align="stretch" gap={5}>
      <SimpleGrid columns={{ base: 2, md: 4 }} gap={{ base: 3, md: 5 }}>
        <StatCard
          label="Users"
          value={formatNumber(stats.total_users)}
          hint={`${formatNumber(stats.active_users)} active`}
          accent
        />
        <StatCard
          label="Submissions"
          value={formatNumber(totalSubmissions)}
          hint={`${formatNumber(stats.total_reviews)} reviews written`}
          delay={0.05}
        />
        <StatCard
          label="Input tokens"
          value={formatNumber(stats.total_input_tokens)}
          hint="Sent to the model"
          delay={0.1}
        />
        <StatCard
          label="Output tokens"
          value={formatNumber(stats.total_output_tokens)}
          hint="Generated by the model"
          delay={0.15}
        />
      </SimpleGrid>
      <GlassCard hoverable={false} delay={0.2} data-testid="submissions-by-status">
        <Text fontSize="xs" textTransform="uppercase" letterSpacing="wider" color="fg.subtle" mb={3}>
          Submissions by status
        </Text>
        <HStack gap={4} flexWrap="wrap">
          {SUBMISSION_STATUSES.map((status) => (
            <HStack key={status} gap={2}>
              <StatusBadge status={status} />
              <Text fontFamily="mono" fontWeight="semibold">
                {formatNumber(stats.submissions_by_status[status] ?? 0)}
              </Text>
            </HStack>
          ))}
        </HStack>
      </GlassCard>
    </VStack>
  )
}
